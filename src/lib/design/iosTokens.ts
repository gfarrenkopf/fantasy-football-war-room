/**
 * Generates the iOS app's design tokens (mobile/ios/DraftRoom/Design/Tokens.swift) from the web's,
 * so the two platforms can't drift. Colors come from the `@theme` block in src/app/globals.css, the
 * source of the Tailwind utilities; the type scale, corner radii and spacing come from the front
 * matter of DESIGN.md, which is where the web's design system records them. `npm run ios:tokens`
 * writes the file, and iosTokens.test.ts fails when the committed copy is stale.
 *
 * Pure: takes the two files' text, returns the Swift source.
 */

export class TokenError extends Error {}

/** `--name: value` pairs from the `@theme { ... }` block, in source order. */
export function parseTheme(css: string): Map<string, string> {
  const start = css.search(/@theme\s*\{/);
  if (start < 0) throw new TokenError("globals.css has no @theme block");
  const end = css.indexOf("}", start);
  const body = css.slice(css.indexOf("{", start) + 1, end).replace(/\/\*[\s\S]*?\*\//g, "");
  const vars = new Map<string, string>();
  for (const m of body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) vars.set(m[1], m[2].trim());
  return vars;
}

/** Follows `var(--x)` aliases to a literal value. */
function resolve(vars: Map<string, string>, name: string, seen: string[] = []): string {
  const value = vars.get(name);
  if (value === undefined) throw new TokenError(`--${seen.at(-1) ?? name} refers to undefined --${name}`);
  const alias = /^var\(--([\w-]+)\)$/.exec(value);
  if (!alias) return value;
  if (seen.includes(alias[1])) throw new TokenError(`--${name} is part of an alias cycle`);
  return resolve(vars, alias[1], [...seen, name]);
}

type Scalar = string | number;
type Section = Record<string, Record<string, Scalar> | Scalar>;

/**
 * The `typography`, `rounded` and `spacing` maps from DESIGN.md's YAML front matter. A small reader
 * for the shape that file uses (two levels of indented `key: value`), not a general YAML parser.
 */
export function parseDesignFrontMatter(md: string): Record<"typography" | "rounded" | "spacing", Section> {
  const fm = /^---\n([\s\S]*?)\n---/.exec(md);
  if (!fm) throw new TokenError("DESIGN.md has no front matter");
  const out: Record<string, Section> = {};
  let section: Section | undefined;
  let entry: Record<string, Scalar> | undefined;
  for (const line of fm[1].split("\n")) {
    const m = /^( *)([\w-]+):\s*(.*)$/.exec(line);
    if (!m) continue;
    const [, indent, key, raw] = m;
    const value = raw === "" ? undefined : scalar(raw);
    if (indent.length === 0) {
      section = value === undefined ? (out[key] = {}) : undefined;
    } else if (indent.length === 2 && section) {
      if (value === undefined) section[key] = entry = {};
      else section[key] = value;
    } else if (indent.length === 4 && entry && value !== undefined) {
      entry[key] = value;
    }
  }
  for (const name of ["typography", "rounded", "spacing"]) {
    if (!out[name]) throw new TokenError(`DESIGN.md front matter has no ${name} map`);
  }
  return out as Record<"typography" | "rounded" | "spacing", Section>;
}

function scalar(raw: string): Scalar {
  const s = raw.trim().replace(/^"(.*)"$/, "$1");
  return /^-?\d+(\.\d+)?$/.test(s) ? Number(s) : s;
}

/** `row-line` → `rowLine`; a leading digit gets an underscore (`2xl` → `_2xl`). */
export function swiftName(token: string): string {
  const name = token.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
  return /^\d/.test(name) ? `_${name}` : name;
}

/** `12.5px` → 12.5. Anything that isn't a plain px length (clamp(), em, %) returns null. */
function px(value: Scalar | undefined): number | null {
  if (typeof value === "number") return value;
  const m = /^(-?\d+(?:\.\d+)?)px$/.exec(String(value ?? "").trim());
  return m ? Number(m[1]) : null;
}

function num(n: number): string {
  return Number.isInteger(n) ? `${n}` : `${Number(n.toFixed(4))}`;
}

function hexToRgb(hex: string, token: string): [number, number, number, number] {
  const m = /^#([0-9a-f]{3,8})$/i.exec(hex);
  const h = m?.[1];
  if (!h || ![3, 4, 6, 8].includes(h.length)) throw new TokenError(`--color-${token} is not a hex color: ${hex}`);
  const full = h.length <= 4 ? [...h].map((c) => c + c).join("") : h;
  const byte = (i: number) => parseInt(full.slice(i, i + 2), 16) / 255;
  return [byte(0), byte(2), byte(4), full.length === 8 ? byte(6) : 1];
}

const WEIGHTS: Record<number, string> = {
  100: "ultraLight",
  200: "thin",
  300: "light",
  400: "regular",
  500: "medium",
  600: "semibold",
  700: "bold",
  800: "heavy",
  900: "black",
};

export function generateSwiftTokens(css: string, designMd: string): string {
  const vars = parseTheme(css);
  const design = parseDesignFrontMatter(designMd);
  const lines: string[] = [
    "// Generated by `npm run ios:tokens` from src/app/globals.css (@theme) and DESIGN.md.",
    "// Do not edit: change the web tokens and regenerate. src/lib/design/iosTokens.test.ts fails",
    "// when this file is stale.",
    "",
    "import SwiftUI",
    "",
    "// MARK: Colors (sRGB), from --color-* in globals.css",
    "",
    "extension ShapeStyle where Self == Color {",
  ];
  for (const name of vars.keys()) {
    if (!name.startsWith("color-")) continue;
    const token = name.slice("color-".length);
    const [r, g, b, a] = hexToRgb(resolve(vars, name), token);
    lines.push(
      `    static var ${swiftName(token)}: Color { Color(.sRGB, red: ${num(r)}, green: ${num(g)}, blue: ${num(b)}, opacity: ${num(a)}) }`,
    );
  }
  lines.push("}", "");

  lines.push(
    "// MARK: Type scale, from DESIGN.md typography (web px; Typography.swift maps it to iOS)",
    "",
    "struct TypeToken: Sendable {",
    "    let size: CGFloat",
    "    let weight: Font.Weight",
    "    let lineHeight: CGFloat",
    "    /// Letter spacing in points at `size`.",
    "    let tracking: CGFloat",
    "}",
    "",
    "enum TypeScale {",
  );
  for (const [role, spec] of Object.entries(design.typography)) {
    if (typeof spec !== "object") continue;
    const size = px(spec.fontSize);
    // Fluid web-only roles (clamp() sizes on the landing page) have no fixed iOS equivalent.
    if (size === null) continue;
    const weight = WEIGHTS[Number(spec.fontWeight ?? 400)];
    if (!weight) throw new TokenError(`typography.${role} has an unknown fontWeight ${spec.fontWeight}`);
    const ls = String(spec.letterSpacing ?? "0");
    const em = /^(-?[\d.]+)em$/.exec(ls);
    const tracking = em ? Number(em[1]) * size : (px(ls) ?? 0);
    lines.push(
      `    static let ${swiftName(role)} = TypeToken(size: ${num(size)}, weight: .${weight}, lineHeight: ${num(Number(spec.lineHeight ?? 1.2))}, tracking: ${num(tracking)})`,
    );
  }
  lines.push("}", "");

  const radii: [string, number][] = [];
  const card = vars.get("radius-card");
  if (card !== undefined) radii.push(["card", px(resolve(vars, "radius-card")) ?? 0]);
  for (const [k, v] of Object.entries(design.rounded)) {
    const n = px(v as Scalar);
    if (n !== null) radii.push([k, n]);
  }
  lines.push("// MARK: Corner radii, from --radius-* in globals.css and DESIGN.md rounded", "", "enum Radius {");
  for (const [k, n] of radii) lines.push(`    static let ${swiftName(k)}: CGFloat = ${num(n)}`);
  lines.push("}", "");

  lines.push("// MARK: Spacing, from DESIGN.md spacing", "", "enum Spacing {");
  for (const [k, v] of Object.entries(design.spacing)) {
    const n = px(v as Scalar);
    if (n !== null) lines.push(`    static let ${swiftName(k)}: CGFloat = ${num(n)}`);
  }
  lines.push("}", "");
  return lines.join("\n");
}
